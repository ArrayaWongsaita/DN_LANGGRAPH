let products: Product[] = structuredClone([...INITIAL_PRODUCTS]);

export function listProducts(): Product[] {
  return structuredClone(products);
}

export function getProduct(id: string): Product | undefined {
  const found = products.find((x) => x.id === id.trim().toUpperCase());
  return found && structuredClone(found);
}

export function getStock(id: string): number | undefined {
  return getProduct(id)?.stock;
}

export function searchProducts(query: ProductQuery): Product[] {
  const words = (query.keyword ?? "").toLowerCase().split(/\s+/).filter((w) => w !== "");
  const hits = products.filter((x) => {
    if (query.category != null && x.category !== query.category) return false;
    if (query.maxPrice != null && x.price > query.maxPrice) return false;
    const haystack = [x.name, ...x.tags, CATEGORY_LABELS[x.category]].join(" ").toLowerCase();
    return words.every((w) => haystack.includes(w));
  });
  return structuredClone(hits);
}

/** ใช้จาก orders.ts เท่านั้น (ตอนยกเลิกคำสั่งซื้อเพื่อคืนสต็อก) */
export function adjustStock(id: string, delta: number): void {
  const found = products.find((x) => x.id === id);
  if (found) found.stock += delta;
}

export function resetProducts(): void {
  products = structuredClone([...INITIAL_PRODUCTS]);
}
